import assert from 'node:assert/strict'
import test from 'node:test'

import { buildNames, buildSprite } from './generate-icon-sprite.mjs'

test('sprite symbols use stable source filename IDs', async () => {
  const sprite = await buildSprite({
    'question-mark-circle': '<svg viewBox="0 0 24 24"><path d="M1 1h1"/></svg>',
    'information-circle': '<svg viewBox="0 0 24 24"><path d="M2 2h2"/></svg>',
  })

  assert.match(sprite, /<symbol id="information-circle" viewBox="0 0 24 24">/)
  assert.match(sprite, /<symbol id="question-mark-circle" viewBox="0 0 24 24">/)
  assert.ok(sprite.indexOf('id="information-circle"') < sprite.indexOf('id="question-mark-circle"'))
})

test('generated TypeScript names mirror source filenames', () => {
  assert.equal(
    buildNames(['plus', 'information-circle']),
    '// Generated by scripts/generate-icon-sprite.mjs — do not edit.\nexport type IconName = "information-circle" | "plus"\n',
  )
})
