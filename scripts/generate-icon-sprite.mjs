import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { optimize } from 'svgo'

const ROOT = path.join(import.meta.dirname, '..')

const OUTPUT = path.join(ROOT, 'app/assets/icons/sprite.svg'),
 SOURCE = path.join(ROOT, 'app/assets/icons/source'),
 SVG_EXTENSION_LENGTH = 4,
 TYPES = path.join(ROOT, 'app/assets/icons/icon-name.ts')

export async function buildSprite(sources) {
  const symbols = await Promise.all(
    Object.entries(sources).toSorted(([a], [b]) => a.localeCompare(b)).map(async ([name, source]) => {
      const optimized = optimize(source, { multipass: true }).data
      const match = optimized.match(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/)
      if (!match) throw new Error(`Could not parse SVG source for ${name}`)
      const viewBox = match[1].match(/\bviewBox="([^"]+)"/)?.[1]
      if (!viewBox) throw new Error(`SVG source for ${name} must have a viewBox`)
      return `<symbol id="${name}" viewBox="${viewBox}">${match[2]}</symbol>`
    }),
  )
  return `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('')}</svg>\n`
}

export function buildNames(names) {
  return `// Generated by scripts/generate-icon-sprite.mjs — do not edit.\nexport type IconName = ${names
    .toSorted((a, b) => a.localeCompare(b))
    .map((name) => JSON.stringify(name))
    .join(' | ')}\n`
}

export async function generateIconSprite() {
  const files = await readdir(SOURCE),
   names = files.filter((file) => file.endsWith('.svg')).map((file) => file.slice(0, -SVG_EXTENSION_LENGTH)),
   sources = Object.fromEntries(await Promise.all(names.map(async (name) => [name, await readFile(path.join(SOURCE, `${name}.svg`), 'utf8')]))),
   sprite = await buildSprite(sources)
  await writeFile(OUTPUT, sprite)
  await writeFile(TYPES, buildNames(names))
  console.log(`Generated sprite and types for ${names.length} icons`)
}

if (process.argv[1] && import.meta.filename === process.argv[1]) await generateIconSprite()
